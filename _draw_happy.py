from PIL import Image, ImageDraw
image = Image.new('RGBA', (64, 64), (0, 0, 0, 0))
draw = ImageDraw.Draw(image)
outline = (92, 64, 52, 255)
face = (249, 214, 112, 255)
mouth = (164, 72, 72, 255)
draw.ellipse((6, 6, 58, 58), fill=face, outline=outline, width=4)
draw.arc((15, 14, 29, 28), 200, 350, fill=outline, width=4)
draw.arc((35, 14, 49, 28), 190, 340, fill=outline, width=4)
draw.pieslice((16, 27, 48, 54), 15, 165, fill=mouth, outline=outline, width=3)
draw.ellipse((19, 22, 26, 29), fill=outline)
draw.ellipse((38, 22, 45, 29), fill=outline)
image.save(r'WelCome/Assets/Art/OpenShop/customer_mood_happy.png')
print(image.size)
